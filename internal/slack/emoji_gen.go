//go:build ignore

// emoji_gen writes emoji.txt from iamcal/emoji-data's emoji.json on
// standard input: each emoji and Slack's own names for it, a line each.
// See emoji.go.
//
//	curl -sSf https://raw.githubusercontent.com/iamcal/emoji-data/master/emoji.json | go run emoji_gen.go > emoji.txt
package main

import (
	"bufio"
	"encoding/json"
	"fmt"
	"os"
	"slices"
	"strconv"
	"strings"
)

type entry struct {
	Unified    string   `json:"unified"`
	ShortName  string   `json:"short_name"`
	ShortNames []string `json:"short_names"`
	SortOrder  int      `json:"sort_order"`
}

func main() {
	var data []entry
	if err := json.NewDecoder(os.Stdin).Decode(&data); err != nil {
		fail(err)
	}
	slices.SortStableFunc(data, func(a, b entry) int { return a.SortOrder - b.SortOrder })
	w := bufio.NewWriter(os.Stdout)
	fmt.Fprintln(w, "// Generated by emoji_gen.go from iamcal/emoji-data (https://github.com/iamcal/emoji-data, MIT licence, Copyright (c) 2013 Cal Henderson); do not edit.")
	fmt.Fprintln(w, "// Each line is an emoji and Slack's names for it, the first the one it prefers.")
	seen := map[string]bool{}
	for _, e := range data {
		if strings.HasPrefix(e.ShortName, "skin-tone-") {
			continue // a skin tone alone, which is a reaction's modifier
		}
		var rs []rune
		for _, h := range strings.Split(e.Unified, "-") {
			n, err := strconv.ParseUint(h, 16, 32)
			if err != nil {
				fail(err)
			}
			rs = append(rs, rune(n))
		}
		names := append([]string{e.ShortName}, slices.DeleteFunc(slices.Clone(e.ShortNames), func(s string) bool { return s == e.ShortName })...)
		for _, n := range names {
			if n == "" || seen[n] || strings.ContainsAny(n, " \t:/") {
				fail(fmt.Errorf("name %q", n))
			}
			seen[n] = true
		}
		fmt.Fprintln(w, string(rs), strings.Join(names, " "))
	}
	if err := w.Flush(); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "emoji_gen:", err)
	os.Exit(1)
}
