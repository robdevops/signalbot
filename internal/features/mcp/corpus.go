package mcp

import "regexp"

// ordinary reports whether re matches nothing at all, or any of a list of
// ordinary chat lines: a pattern that does would turn a watch into a feed
// of the chat, so it is refused.
func ordinary(re *regexp.Regexp) bool {
	if re.MatchString("") {
		return true
	}
	for _, line := range chatter {
		if re.MatchString(line) {
			return true
		}
	}
	return false
}

